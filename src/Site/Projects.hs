-- | Directly maintained project copy, shared by the project card and the
-- project's detail page.
--
-- Phase 01 deliberately keeps this as plain Haskell values: there is no
-- loader, schema or Markdown. Phase 02 replaces it with the typed content
-- pipeline.
module Site.Projects
  ( Project (..)
  , ProjectSection (..)
  , SectionContent (..)
  , projectTitleId
  , brigid
  ) where

import Data.Text qualified as T

import Brigid.Types qualified as B

import Site.Assets qualified as Asset
import Site.Routes (Slug, elementId, slugText)

data Project =
  Project
    { projectSlug :: Slug
    , projectName :: T.Text
    , projectKicker :: T.Text
      -- ^ Kind and status, e.g. "Haskell library · In development".
    , projectSummary :: T.Text
      -- ^ One sentence, for the card and the detail page's subtitle.
    , projectTags :: [T.Text]
    , projectCardArt :: Asset.Asset
    , projectSections :: [ProjectSection]
      -- ^ The detail page's sections, in order. The project sidebar is
      -- generated from this list, so every sidebar entry has a section.
    }

-- | One anchored section of a project page.
data ProjectSection =
  ProjectSection
    { sectionId :: B.Id
    , sectionLabel :: T.Text
      -- ^ The section's heading, also its sidebar entry.
    , sectionContent :: SectionContent
    }

data SectionContent
  = Paragraphs [T.Text]
  | Facts [(T.Text, T.Text)]
    -- ^ Term/description pairs.
  | Links [(T.Text, T.Text)]
    -- ^ Label/URL pairs (external links).

-- | The id of the project's title, @{slug}-title@ (labels the card).
projectTitleId :: Project -> B.Id
projectTitleId project = elementId (slugText (projectSlug project) <> "-title")

-- | Brigid. Facts are taken from the library's README and package metadata
-- at the commit this site pins (@9344bfb@).
brigid :: Slug -> Project
brigid slug =
  Project
    { projectSlug = slug
    , projectName = "Brigid"
    , projectKicker = "Haskell library · In development"
    , projectSummary = "Type-safe, (mostly) spec-compliant HTML for Haskell. This page is rendered with it."
    , projectTags = [ "Haskell", "HTML", "Type safety" ]
    , projectCardArt = Asset.cardBrigid
    , projectSections =
        [ ProjectSection (elementId "overview") "Overview" . Paragraphs $
            [ "Brigid is a Haskell library for constructing and rendering HTML, and HXML, with the structure of the document checked by the type system."
            , "Each element states which children it may contain, so many invalid documents are rejected when the program is compiled rather than discovered in a browser. The library describes its output as “(mostly) spec-compliant”: the types capture many of the specification’s content rules, not yet all of them."
            , "This site is its first portfolio-scale user: every page here is generated by a small Haskell program that builds its markup with Brigid."
            ]
        , ProjectSection (elementId "technical-details") "Technical details" . Facts $
            [ ("Language", "Haskell")
            , ("Builds", "HTML and HXML documents")
            , ("Renders to", "ByteString, Text or String")
            , ("Status", "In active development; the API is not yet stable")
            , ("Licence", "BSD-3-Clause")
            ]
        , ProjectSection (elementId "resources") "Resources" . Links $
            [ ("Source code on GitHub", "https://github.com/AugmenTab/brigid") ]
        ]
    }
