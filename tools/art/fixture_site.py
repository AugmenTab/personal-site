"""Build a throwaway fixture tree for Phase 05 evidence (development only).

    docker compose --profile tools run --rm art python3 tools/art/fixture_site.py
    docker compose run --rm site-build stack exec -- \
        site build --root .local/fixture-site --out .local/fixture-site/html
    docker compose --profile tools up -d fixture-preview      # http://localhost:8082/

The real site has no published article and no résumé, so the Writing
section and the Résumé link do not exist there. To show (and browser-check)
what they look like, this writes .local/fixture-site/ (git-ignored): a copy
of content/ and assets/ plus

  - content/writing/fixture-article/: a published article whose title, summary
    and text say plainly that it is a layout fixture;
  - content/writing/fixture-draft/: a draft, to prove it stays unpublished;
  - content/resume.pdf: a one-page PDF that says it is a fixture, not a
    résumé.

The repository's content/ is never touched: nothing here can be committed or
published by accident.
"""

import json
import os
import shutil
import sys

from PIL import Image, ImageDraw, ImageFont

from common import chown_like_work

ROOT = ".local/fixture-site"

ARTICLE_BODY = """This page is a layout fixture for the Writing section. It is generated by
`tools/art/fixture_site.py` into a throwaway tree and is never published.

## Why it exists

The site shows Writing only when an article is published. None is yet, so
this fixture lets the index, the article layout and the navigation be
reviewed and browser-checked without inventing a real post.

## What it shows

- The Writing link in the navigation and the footer.
- The Writing preview on the homepage.
- An article with sections, a list and `inline code`.

> Replace this fixture with a real article in `content/writing/` when one is
> ready; see README "Publishing a Writing article".
"""


def font(size):
    try:
        return ImageFont.load_default(size=size)
    except TypeError:
        return ImageFont.load_default()


def write_json(path, value):
    with open(path, "w") as f:
        json.dump(value, f, indent=2, ensure_ascii=False)
        f.write("\n")


def article(slug, title, summary, status, date, body):
    directory = f"{ROOT}/content/writing/{slug}"
    os.makedirs(directory, exist_ok=True)
    write_json(f"{directory}/article.json", {
        "slug": slug,
        "title": title,
        "summary": summary,
        "publication_status": status,
        "date": date,
        "body": "body.md",
    })
    with open(f"{directory}/body.md", "w") as f:
        f.write(body)


def resume_pdf(path):
    """A one-page A4 PDF that states it is a fixture."""
    page = Image.new("RGB", (1240, 1754), "white")
    d = ImageDraw.Draw(page)
    d.text((120, 160), "LAYOUT FIXTURE", fill="black", font=font(72))
    d.text((120, 280), "This is not a résumé. It stands in for content/resume.pdf", fill="black", font=font(36))
    d.text((120, 330), "so the navigation's Résumé link can be reviewed.", fill="black", font=font(36))
    d.text((120, 400), "Generated by tools/art/fixture_site.py; never published.", fill="black", font=font(36))
    page.save(path, "PDF", resolution=150.0)


def main() -> int:
    os.makedirs(ROOT, exist_ok=True)
    for name in ("content", "assets"):
        shutil.rmtree(f"{ROOT}/{name}", ignore_errors=True)
        shutil.copytree(name, f"{ROOT}/{name}", symlinks=False)

    article(
        "fixture-article",
        "Layout fixture: a Writing article",
        "A placeholder used only to review the Writing layout. Not published on the real site.",
        "published",
        "2026-11-15",
        ARTICLE_BODY,
    )
    article(
        "fixture-draft",
        "Draft fixture that must stay unpublished",
        "If this appears anywhere in the built fixture site, draft filtering is broken.",
        "draft",
        "2026-11-16",
        "## Draft\n\nNever rendered.\n",
    )
    resume_pdf(f"{ROOT}/content/resume.pdf")

    for dirpath, _dirnames, filenames in os.walk(ROOT):
        chown_like_work(dirpath, *(os.path.join(dirpath, n) for n in filenames))
    print(f"fixture tree: {ROOT}/ (copies of content/ and assets/, plus a fixture article, a draft and resume.pdf)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
